// Builds src/rules/registry.generated.ts from the rule tables of the spec tabs.
// Usage: node scripts/gen-rules.mjs [specs folder]   (default: .artifacts/specs)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? ".artifacts/specs";
const VIS = [
  [/chart choice|honesty|uncertainty/i, "visualization/charts.md"],
  [/colour|style|titles|text|tables|theme/i, "visualization/style.md"],
  [/filters|layout|exports|accessibility|fonts/i, "visualization/page.md"],
];
const clean = (s) =>
  s
    .replace(/\\([_\[\]|*])/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .trim();
const cells = (line) =>
  line
    .split(/(?<!\\)\|/)
    .slice(1, -1)
    .map((c) => c.trim());
const rules = [];

function parse(file, fileFor) {
  let heading = "";

  for (const line of readFileSync(join(dir, file), "utf8").split("\n")) {
    if (line.startsWith("#")) heading = line.replace(/^#+\s*/, "");

    const m = /^\| ([A-Z]\d+) \|/.exec(line);

    if (!m) continue;

    const c = cells(line);
    const id = c[0];

    if (rules.some((r) => r.id === id)) continue;

    const deploy = id.startsWith("H");

    rules.push({
      id,
      level: /^Must/.test(deploy ? c[2] : c[3]) ? "must" : "should",
      text: clean(c[1]),
      pitfall: deploy ? "" : clean(c[2]),
      field: deploy ? "" : clean(c[4]).replace(/`/g, ""),
      file: fileFor(id, heading),
    });
  }
}

parse("Benchmark skill research.md", (id, h) => {
  const m = /^([\w/]+\.md)/.exec(h);

  if (m) return m[1];

  return id.startsWith("S") ? "statistics.md" : "SKILL.md";
});
parse("Visualization skill research.md", (_id, h) => VIS.find(([re]) => re.test(h))?.[1] ?? "visualization/charts.md");
parse("Deployment (deploy.md).md", () => "deploy.md");

const num = (id) => [id[0], Number(id.slice(1))];

rules.sort((a, b) => (num(a.id)[0] === num(b.id)[0] ? num(a.id)[1] - num(b.id)[1] : a.id < b.id ? -1 : 1));
const out =
  "// Generated by scripts/gen-rules.mjs from the spec tabs. Do not edit by hand.\n" +
  'import type { Rule } from "./registry.js";\n\n' +
  `export const RULES: Rule[] = ${JSON.stringify(rules, null, 2)};\n`;

writeFileSync("src/rules/registry.generated.ts", out);
console.log(`${rules.length} rules written`);
